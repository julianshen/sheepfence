import Foundation
import Testing
@testable import SheepFence

private actor HeldFailingTransport: URLTransport {
    let started = AsyncStream<Void>.makeStream()
    private var pending: CheckedContinuation<Void, Never>?
    func data(from url: URL, maximumBytes: Int) async throws -> (Data, URLResponse) {
        await withCheckedContinuation { continuation in
            pending = continuation
            started.continuation.yield()
        }
        throw URLError(.notConnectedToInternet)
    }
    func failNow() { pending?.resume(); pending = nil }
}

struct SDKReplacementTests {
    @Test func realReplacementDeletionExpansionAndConcurrentDownloadFailure() async throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        let storeURL = root.appendingPathComponent("snapshot.sqlite")
        let store = try CoreDataSnapshotStore(url: storeURL)
        let transport = HeldFailingTransport()
        let source = HTTPSnapshotSource(policy: .standard, transport: transport)
        let engine = GeofenceEngine(configuration: try .init(maximumLocationAge: 1000), store: store,
            source: source, decoder: { try GeoJSONDecoder.decode($0) },
            geometry: .init(contains: { Geometry.contains($0, in: $1) }, distance: { Geometry.distanceToBoundary($0, in: $1) }),
            clock: FixedClock(time: Date(timeIntervalSince1970: 2000)))
        let fixture = try #require(Bundle.module.url(forResource: "campus-v3", withExtension: "geojson"))
        _ = try await engine.installSnapshot(from: fixture)
        try await engine.startMonitoring(mode: .hostProvided)
        let sample = LocationSample(coordinate: .init(longitude: 10.001, latitude: 20.002),
                                    timestamp: Date(timeIntervalSince1970: 1100), horizontalAccuracy: 1)
        let baseline = try await engine.submit(location: sample)
        #expect(baseline.results.first { $0.regionID.featureID == "garden" }?.observation == .confirmed(.outside))
        let stream = try await engine.eventStream()
        var events = stream.makeAsyncIterator()
        _ = try await events.next()

        let failedDownload = Task { try await engine.installSnapshot(from: URL(string: "https://example.invalid/snapshot")!) }
        var began = transport.started.stream.makeAsyncIterator()
        _ = await began.next() // transport is suspended before failing, concurrently with replacement
        defer { Task { await transport.failNow() } }
        var replacement = try #require(JSONSerialization.jsonObject(with: Data(contentsOf: fixture)) as? [String: Any])
        var metadata = try #require(replacement["dataset"] as? [String: Any])
        metadata["revision"] = 4; replacement["dataset"] = metadata
        let features = try #require(replacement["features"] as? [[String: Any]])
        var garden = try #require(features.first { $0["id"] as? String == "garden" })
        garden["geometry"] = ["type": "Polygon", "coordinates": [[[10.000,20.001],[10.004,20.001],[10.004,20.003],[10.000,20.003],[10.000,20.001]]]]
        replacement["features"] = [garden] // remove campus and expand garden in the same commit
        let bytes = try JSONSerialization.data(withJSONObject: replacement)
        #expect(try await engine.install(data: bytes).activeRevision == 4)
        await transport.failNow()
        await #expect(throws: GeofenceError.sourceFailed(.network)) { try await failedDownload.value }
        guard case .datasetChanged(let change)? = try await events.next() else { Issue.record("expected dataset change, not crossing"); return }
        #expect(change.removedRegionIDs.map(\.featureID) == ["campus"])
        #expect(change.evaluations.first?.observation == .confirmed(.inside))
        let gardenID = RegionID(datasetID: "com.example.campus", featureID: "garden")
        #expect(try await engine.query(coordinate: sample.coordinate, in: gardenID).revision == 4)
        await #expect(throws: GeofenceError.regionNotFound(.init(datasetID: gardenID.datasetID, featureID: "campus"))) {
            try await engine.query(coordinate: sample.coordinate, in: .init(datasetID: gardenID.datasetID, featureID: "campus"))
        }
        await engine.stopMonitoring()
        // Stop availability is next: no synthetic enter/exit was generated by the redraw/failure.
        #expect(try await events.next() == .locationAvailabilityChanged(.init(reason: .monitoringStopped)))
        let restored = try await CoreDataSnapshotStore(url: storeURL).loadCommittedSnapshots()
        #expect(restored.first?.metadata.revision == 4)
        #expect(restored.first?.regions.map(\.id.featureID) == ["garden"])
    }
}
